CREATE TABLE tutor_reviews (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               student_id BIGINT NOT NULL,
                               tutor_id BIGINT NOT NULL,
                               rating NUMERIC(2, 1) NOT NULL,
                               comment VARCHAR(2000),
                               created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                               updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,

                               CONSTRAINT fk_tutor_reviews_student
                                   FOREIGN KEY (student_id) REFERENCES users (id),
                               CONSTRAINT fk_tutor_reviews_tutor
                                   FOREIGN KEY (tutor_id) REFERENCES users (id),
                               CONSTRAINT uk_tutor_review_student_tutor
                                   UNIQUE (student_id, tutor_id),
                               CONSTRAINT chk_tutor_reviews_rating
                                   CHECK (rating >= 1.0 AND rating <= 5.0)
);

CREATE INDEX idx_tutor_reviews_tutor_created_at
    ON tutor_reviews (tutor_id, created_at DESC);